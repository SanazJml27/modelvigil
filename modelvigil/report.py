"""Post-market monitoring report (EU AI Act Art. 72 / MDR Arts. 83-86 style)
and a timeline figure for a single surveillance run."""
from __future__ import annotations

from pathlib import Path

from .config import ALERT_THRESHOLD, PCCP_PLAN, THRESHOLDS


def timeline_plot(result: dict, path: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    W = result["weekly"]
    wk = [r["week"] for r in W]
    sw = result["config"]["shift_week"]
    fig, axes = plt.subplots(3, 1, figsize=(10, 7.5), sharex=True)

    ax = axes[0]
    ax.plot(wk, [r["score"]["alert_rate"] * 100 for r in W], "-o", ms=3, color="#1b6e8a", label="alert rate (live)")
    ax.plot(wk, [r["oracle"]["no_monitoring"]["alerts"] / r["oracle"]["no_monitoring"]["n"] * 100 for r in W],
            "--", color="#999", label="alert rate (no monitoring)")
    ax.set_ylabel("% patients alerted")
    ax.legend(fontsize=8, loc="upper left")

    ax = axes[1]
    ax.plot(wk, [r["cbpe_auroc"] for r in W], "-o", ms=3, color="#c98a2b", label="expected AUROC (label-free)")
    ax.plot(wk, [r["oracle"]["live"].get("auroc") for r in W], ":", color="#1b6e8a", label="true AUROC (oracle, live)")
    ax.plot(wk, [r["domain_auc"] for r in W], "-s", ms=3, color="#7a4ea3", label="drift classifier AUROC")
    ax.axhline(THRESHOLDS.domain_auc, color="#7a4ea3", lw=0.6, ls="--")
    ax.set_ylabel("AUROC")
    ax.legend(fontsize=8, loc="lower left")

    ax = axes[2]
    oe = [(r["labelled"] or {}).get("oe") for r in W]
    ax.plot(wk, oe, "-o", ms=3, color="#1b6e8a", label="O/E on lagged labels (monitor view)")
    ax.plot(wk, [r["oracle"]["live"].get("oe") for r in W], ":", color="#555", label="O/E this week (oracle)")
    ax.axhspan(THRESHOLDS.oe_low, THRESHOLDS.oe_high, color="#1b6e8a", alpha=0.07)
    ax.set_ylabel("observed / expected")
    ax.set_xlabel("deployment week")
    ax.legend(fontsize=8, loc="upper left")

    for a in axes:
        a.axvline(sw - 0.5, color="crimson", lw=1)
        for inc in result["incidents"]:
            a.axvline(inc["opened_week"], color="#333", lw=0.8, ls="--")
        a.spines[["top", "right"]].set_visible(False)
    axes[0].text(sw - 0.4, axes[0].get_ylim()[1] * 0.95, "shift", color="crimson", fontsize=8, va="top")
    for inc in result["incidents"]:
        axes[0].text(inc["opened_week"] + 0.1, axes[0].get_ylim()[1] * 0.80,
                     inc["diagnosis"]["root_cause"].replace("_", " "), fontsize=7, rotation=90, va="top")
    fig.suptitle(f"ModelVigil - scenario '{result['config']['scenario']}' (seed {result['config']['seed']})", fontsize=11)
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def _tbl(rows, headers):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def pms_report(result: dict, audit_ok: tuple[bool, str] | None = None) -> str:
    c, b = result["config"], result["baseline"]
    L = [f"# Post-Market Monitoring Report - 48h Deterioration Model",
         "",
         f"*Generated by ModelVigil. Scenario `{c['scenario']}` (synthetic data), seed {c['seed']}, "
         f"diagnostician backend `{c['llm']}`, approval mode `{c['approval']}`.*",
         "",
         "> Structure follows the post-market monitoring obligations of the EU AI Act (Art. 72) and "
         "MDR post-market surveillance (Arts. 83-86). It is a technical demonstrator, not a regulatory submission.",
         "",
         "## 1. System under surveillance",
         "",
         f"- Intended use: flag adult inpatients at risk of unplanned ICU transfer or death within 48 h; alert at "
         f"risk >= {ALERT_THRESHOLD:.0%} triggers rapid-response review.",
         f"- Initial version 1.0.0; final version **{result['final_model']['version']}** "
         f"({result['final_model']['note']}), fingerprint `{result['final_model']['fingerprint']}`.",
         f"- Validation baseline: AUROC {b['auroc']:.3f}, O/E {b['oe']:.2f}, alert rate {b['alert_rate']:.1%}.",
         f"- Monitoring period: {c['n_weeks']} weeks, ~{c['n_per_week']} patients/week; outcomes available after a "
         f"2-week lag.",
         "",
         "## 2. Monitoring plan in force",
         "",
         "- Label-free (weekly): data quality (physiological range, single-value spikes by site), multivariate "
         "drift (classifier two-sample test), alert burden, confidence-based expected AUROC, new subgroups.",
         "- Label-based (lagged, rolling): AUROC, O/E with exact Poisson CI, calibration slope, subgroup O/E "
         "(site, sex, age band) with Bonferroni-adjusted limits.",
         f"- Change control (PCCP): pre-authorised = {', '.join(PCCP_PLAN.allowed_auto)}; "
         f"review required = {', '.join(PCCP_PLAN.requires_review)}.",
         "",
         "## 3. Incidents",
         ""]
    if not result["incidents"]:
        L.append("No incidents were opened during the period.")
    for inc in result["incidents"]:
        dx, pl, de = inc["diagnosis"], inc["plan"], inc["decision"]
        L += [f"### {inc['id']} - opened week {inc['opened_week']}",
              "",
              f"**Triggering signals:** {', '.join(f'`{s}`' for s in inc['signals'])}",
              "",
              f"**Root cause:** `{dx['root_cause']}` (confidence {dx['confidence']}; independently verified: "
              f"{'yes' if dx.get('verified') else 'NO'}; backend {dx.get('backend', 'mock')})",
              "",
              f"{dx['rationale']}",
              ""]
        if dx.get("note"):
            L += [f"*Note: {dx['note']}*", ""]
        L += ["Evidence:"] + [f"- {e}" for e in dx.get("evidence", [])] + [""]
        if inc.get("labelled_weeks_used"):
            L += [f"Labelled weeks used for diagnosis: {inc['labelled_weeks_used']} "
                  f"({(inc.get('change_point') or {}).get('method', '')})", ""]
        L += [f"**Investigation trace:** " + " -> ".join(f"`{t['tool']}`" for t in inc["transcript"]), ""]
        L += [f"**Proposed action:** `{pl['action']}` (category `{pl['category']}`)"]
        L += [f"- {r}" for r in pl.get("recommendations", [])]
        if pl.get("candidate"):
            L += [f"- Candidate model {pl['candidate']['version']}: {pl['candidate']['note']}"]
        if pl.get("shadow"):
            rows = [[k, v["auroc"], v["oe"], v["brier"], v["sensitivity"], v["alert_rate"],
                     f"{v['worst_subgroup']} ({v['worst_subgroup_oe_dev']})"] for k, v in pl["shadow"].items()]
            L += ["", "Shadow evaluation on held-out recent labelled data:", "",
                  _tbl(rows, ["config", "AUROC", "O/E", "Brier", "sensitivity", "alert rate", "worst subgroup |O/E-1|"])]
        if pl.get("verification"):
            v = pl["verification"]
            L += ["", f"Pipeline-fix verification on live batch: fault cleared = {v.get('fault_cleared')}; alert rate "
                      f"{v['alert_rate_before']:.1%} -> {v['alert_rate_after']:.1%} (reference {v['alert_rate_reference']:.1%})"]
        L += ["",
              f"**PCCP:** {'inside' if de['pccp']['inside_envelope'] else 'OUTSIDE'} envelope - {'; '.join(de['pccp']['reasons'])}",
              "",
              f"**Decision:** {'APPROVED' if de['approved'] else 'NOT APPROVED'} by {de['approver']}"
              + (f" - {de['review_note']}" if de.get("review_note") else ""),
              ""]
        if de.get("vigilance_flag"):
            L += ["**Vigilance:** potential for patient harm (under-triage or alert flooding). Assess against serious-"
                  "incident reporting criteria (AI Act Art. 73; MDR Art. 87) and document the outcome.", ""]

    im = result["impact"]
    L += ["## 4. Patient-level impact (simulation oracle - not available in real deployment)", "",
          _tbl([["events after shift", im["post_shift_events"], im["post_shift_events"]],
                ["missed deteriorations", im["missed_events_no_monitoring"], im["missed_events_live"]],
                ["alerts", im["alerts_no_monitoring"], im["alerts_live"]],
                ["false alerts", im["false_alerts_no_monitoring"], im["false_alerts_live"]],
                ["net benefit per 1,000 patients", im["net_benefit_per_1000_no_monitoring"],
                 im["net_benefit_per_1000_live"]]],
               ["", "no monitoring", "with ModelVigil"]),
          "",
          "Net benefit = TP/n - FP/n x pt/(1-pt) at the deployed threshold (decision-curve analysis).", "",
          "## 5. Data-pipeline corrections in force", ""]
    L += [f"- {x}" for x in result["pipeline_corrections"]] or ["- none"]
    L += ["", "## 6. Record keeping", "",
          "Every signal, tool call, diagnosis, verification, decision and model/pipeline change is written to a "
          "hash-chained audit log (`audit.jsonl`)."]
    if audit_ok:
        L += [f"Integrity check: **{'PASS' if audit_ok[0] else 'FAIL'}** - {audit_ok[1]}."]
    L += ["", "![timeline](timeline.png)", ""]
    return "\n".join(L)
